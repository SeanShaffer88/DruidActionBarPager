check("reset command stages without mutation", ns.Settings.Mapping().cat==8 and f.token~=nil)
click("Apply reviewed mapping")
check("confirmed reset restores only default mapping", ns.Settings.Mapping().cat==ns.Constants.DEFAULT_PAGES.cat)
ns.Commands.Execute("undo")
check("undo command opens review before mutation", ns.Settings.Mapping().cat==ns.Constants.DEFAULT_PAGES.cat)
click("Apply reviewed mapping")
check("reviewed undo restores preceding mapping", ns.Settings.Mapping().cat==8)
ns.Workflow.Preview("cat",0)
check("page zero does not fabricate twelve action icons", not f.icons[1]:IsShown())
ns.Workflow.Share()
check("share edit view preserves native editing without parent capture", f.edit.editFocus and not f.keyboard and not parent.keyboard)
f.edit:GetScript("OnTabPressed")(f.edit)
check("Tab leaves native edit focus for button navigation", f.keyboard and not f.edit.editFocus)
f.edit:SetFocus()
check("clicking the visible edit field releases both controllers", f.edit.editFocus and not f.keyboard and not parent.keyboard)
local original=ns.Settings.Mapping().cat
f.edit:SetText("DABP1;bear=2;cat=6;travel=0;aquatic=0;moonkin=4;tree=4;prowl=0")
f.edit:GetScript("OnTabPressed")(f.edit)
