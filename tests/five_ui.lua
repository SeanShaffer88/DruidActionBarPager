HasAction = function(slot) return slot == 25 end
local ns = H.load(ADDON_FILES, nil)
local results = {}
local function check(name, ok) results[#results+1] = (ok and "PASS " or "FAIL ") .. name end
local function click(label)
    local f=ns.Workflow.Frame()
    for _,b in ipairs(f.buttons) do if b.text == label then b:GetScript("OnClick")(b); return true end end
    return false
end
local function key(keyName)
    local f=ns.Workflow.Frame()
    check("workflow owns actual keyboard before "..keyName, f.keyboard == true)
    f:GetScript("OnKeyDown")(f,keyName)
end
check("supplied invalid page text is rejected", ns.Workflow.Preview("cat", "nonsense")==false)
for _,invalid in ipairs({-1,11,1.5,math.huge,0/0}) do
    check("invalid numeric preview is rejected", ns.Workflow.Preview("cat",invalid)==false)
end
ns.Commands.Execute("preview cat 2")
local f,parent=ns.Workflow.Frame(),ns.MappingPanel.Frame()
check("preview uses one nonsecure higher child of Mapping", f and f.parent==parent and not f.prot and f:GetFrameLevel()>parent:GetFrameLevel())
check("preview contains twelve ordered native nonsecure icons", #f.icons==12 and f.icons[1]:IsShown() and f.preview.slots[1].slot==13)
check("parent refresh never captures under workflow", not parent.keyboard and f.keyboard)
ns.MappingPanel.Refresh(); check("secure status refresh preserves child keyboard ownership", not parent.keyboard and f.keyboard)
ns.Workflow.Preview("cat",3)
check("native preview uses canonical action texture", f.icons[1].texture.texture==456)
local current=ns.Settings.Mapping().cat
local stale=f.buttons[#f.buttons-1]:GetScript("OnClick")
key("ESCAPE")
check("cancel does not apply proposed mapping and restores parent capture", ns.Settings.Mapping().cat==current and parent.keyboard and not f.keyboard)
ns.Workflow.Reset(); stale()
f.CloseButton:GetScript("OnClick")(f.CloseButton)
check("native X closes child without writing or closing Mapping", not f:IsShown() and parent:IsShown() and ns.Settings.Mapping().cat==current)
ns.Workflow.Reset()
check("old view callback cannot apply a new review", ns.Settings.Mapping().cat==current)
key("ESCAPE")
ns.Commands.Execute("cat 8")
